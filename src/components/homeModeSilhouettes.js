export const getModeClipPath = (modeKey) => {
  const shape = MODE_SILHOUETTE_POLYGONS[modeKey] || MODE_SILHOUETTE_POLYGONS.countries;
  const pts = shape.outer.map(([x, y]) => `${x}% ${y}%`).join(", ");
  return `polygon(${pts})`;
};

export const toSvgPoints = (points, insetX = 0, insetY = 0) =>
  points
    .map(([x, y]) => {
      const sx = x < 50 ? x + insetX : x > 50 ? x - insetX : x;
      const sy = y < 50 ? y + insetY : y > 50 ? y - insetY : y;
      return `${Math.round(sx * 10)},${Math.round(sy * 6)}`;
    })
    .join(" ");
