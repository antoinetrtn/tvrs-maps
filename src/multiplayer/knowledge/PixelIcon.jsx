function buildRuns(rows) {
  const runs = [];
  for (let r = 0; r < rows.length; r += 1) {
    const line = rows[r];
    let start = -1;
    for (let c = 0; c <= line.length; c += 1) {
      if (line[c] === "#") {
        if (start === -1) start = c;
      } else if (start !== -1) {
        runs.push({ key: `${r}-${start}`, row: r + 1, colStart: start + 1, colEnd: c + 1 });
        start = -1;
      }
    }
  }
  return runs;
}

/** Extracts the icon family prefix before the first hyphen (`"tech-cpu"` -> `"tech"`). */
export function resolveIconFamily(iconId) {
  const raw = String(iconId || "")
    .trim()
    .toLowerCase();
  const [prefix] = raw.split("-");
  return prefix in FAMILY_GRIDS ? prefix : "symbol";
}

/**
 * 12x12 CSS pixel-art glyph fallback per icon family (3px square cells = 36x36 px).
 */
const PixelIcon = ({ iconId, className = "" }) => {
  const family = resolveIconFamily(iconId);
  const runs = useMemo(() => buildRuns(FAMILY_GRIDS[family] || FAMILY_GRIDS.symbol), [family]);

  return (
    <span
      className={`cq-pixel-icon cq-pixel-icon--${family}${className ? ` ${className}` : ""}`}
      data-family={family}
      data-icon={iconId || "symbol"}
      aria-hidden="true"
    >
      {runs.map((run) => (
        <span
          key={run.key}
          className="cq-pixel-px"
          style={{
            gridRow: run.row,
            gridColumn: `${run.colStart} / ${run.colEnd}`,
          }}
        />
      ))}
    </span>
  );
};

export default PixelIcon;
